import { useCallback, useEffect, useRef, useState } from "react";
import { getCoaching } from "../lib/coach";
import { useWordStream } from "../hooks/useWordStream";
import type { Choice, Scenario } from "../types";

interface Props {
  scenario: Scenario;
  choice: Choice;
  onBack: () => void;
  onRestart: () => void;
  onHowItWorks: () => void;
}

type Status = "loading" | "ready" | "error";

export function FeedbackScreen({ scenario, choice, onBack, onRestart, onHowItWorks }: Props) {
  const [status, setStatus] = useState<Status>("loading");
  const [feedback, setFeedback] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  const abortRef = useRef<AbortController | null>(null);
  const { shown, done } = useWordStream(feedback, 60);

  const request = useCallback(() => {
    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;
    setStatus("loading");
    setFeedback(null);
    getCoaching(choice.id, controller.signal)
      .then((text) => {
        setFeedback(text);
        setStatus("ready");
      })
      .catch((err) => {
        if (err.name !== "AbortError") setStatus("error");
      });
  }, [choice.id]);

  useEffect(() => {
    request();
    return () => abortRef.current?.abort();
  }, [request]);

  useEffect(() => {
    if (!copied) return;
    const id = window.setTimeout(() => setCopied(false), 2000);
    return () => window.clearTimeout(id);
  }, [copied]);

  const copy = async () => {
    if (!feedback) return;
    try {
      await navigator.clipboard.writeText(feedback);
      setCopied(true);
    } catch {
      // Clipboard can be blocked (e.g. insecure context); nothing useful to show.
    }
  };

  return (
    <section className="screen feedback">
      <div className="your-choice">
        <span className="label">You said</span>
        <p>“{choice.text}”</p>
      </div>

      <div className="speaker">
        <img className="avatar" src={scenario.coach.avatar} alt={scenario.coach.name} />
        <div className="speaker-body">
          <h2>Your Feedback</h2>
          {status === "loading" && (
            <p className="thinking" role="status">
              Coach {scenario.coach.name} is thinking<span className="dots" aria-hidden="true" />
            </p>
          )}
          {status === "error" && (
            <p className="error" role="alert">
              I'm having trouble reaching the coach.{" "}
              <button className="btn btn-link" onClick={request}>
                Try again
              </button>
            </p>
          )}
          {status === "ready" && feedback && (
            <>
              <p className="feedback-text" aria-hidden="true">
                {shown}
              </p>
              <p className="sr-only" role="status">
                {feedback}
              </p>
            </>
          )}

          {done && (
            <div className="feedback-actions">
              <button className="btn btn-ghost" onClick={request}>
                ↻ Regenerate response
              </button>
              <button className="btn btn-ghost" onClick={copy}>
                {copied ? "✓ Copied" : "Copy"}
              </button>
            </div>
          )}
        </div>
      </div>

      {done && (
        <div className="end-bar">
          <button className="btn btn-link" onClick={onHowItWorks}>
            Learn how this works
          </button>
          <button className="btn btn-primary" onClick={onRestart}>
            Restart scenario
          </button>
        </div>
      )}

      <p className="disclaimer">
        Response generated by Gemini AI. AI-generated content may contain inaccuracies.
      </p>

      <button className="btn btn-link back" onClick={onBack}>
        ← Back
      </button>
    </section>
  );
}
